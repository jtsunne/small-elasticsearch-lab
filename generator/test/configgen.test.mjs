const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const fixtures = path.join(here, 'fixtures');
const data = JSON.parse(fs.readFileSync(path.join(fixtures, 'data.json'), 'utf8'));
const scenarioFixtures = fs.readdirSync(fixtures)
	.filter((f) => f !== 'data.json' && f.endsWith('.json'))
	.sort()
	.map((f) => JSON.parse(fs.readFileSync(path.join(fixtures, f), 'utf8')));

// Files in a scenario directory that exist for the lab only (benchmarks, the
// test runner, documentation). Every other file must come from the generator.
const LAB_ONLY = [/^README\.md$/, /^expected\.tsv$/, /^compose\.bench\.yaml$/, /^bodies\//, /^fault-test\.sh$/];

// Tracked plus untracked-but-not-ignored files, so a scenario file added in
// the working tree is checked before it is committed, and a local .env or
// generated certificate is not.
function scenarioFiles(dir) {
	const out = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '-z', '--', dir], { cwd: repo });
	return out.toString().split('\0').filter(Boolean)
		.map((f) => path.relative(dir, f))
		.filter((f) => fs.existsSync(path.join(repo, dir, f)))
		.filter((f) => !LAB_ONLY.some((re) => re.test(f)))
		.sort();
}

function gen(overrides = {}) {
	return generate({ ...DEFAULT_INPUTS, ...overrides }, data);
}

function genOk(overrides = {}) {
	const r = gen(overrides);
	assert.deepEqual(r.errors, [], JSON.stringify(r.errors));
	return r;
}

function body(r, name) {
	assert.ok(name in r.files, `${name} missing from ${Object.keys(r.files).join(', ')}`);
	return stripHeader(r.files[name]);
}

test('fixtures are the generator\'s tested input sets', () => {
	assert.equal(scenarioFixtures.length, Object.keys(TESTED).length);
	for (const fx of scenarioFixtures) {
		const entry = Object.values(TESTED).find((e) => e.path === fx.path);
		assert.ok(entry, `${fx.path} is not in TESTED`);
		assert.deepEqual(fx.inputs, entry.inputs);
	}
});

for (const fx of scenarioFixtures) {
	test(`byte-identical to ${fx.path} after the header is removed`, () => {
		const r = generate(fx.inputs, data);
		assert.deepEqual(r.errors, []);
		assert.deepEqual(r.tested, { tested: true, path: fx.path, reasons: [], differs: [] });
		assert.deepEqual(Object.keys(r.files).sort(), scenarioFiles(fx.path));
		for (const [name, text] of Object.entries(r.files)) {
			const want = fs.readFileSync(path.join(repo, fx.path, name), 'utf8');
			assert.equal(stripHeader(text), want, `${fx.path}/${name} differs`);
			assert.equal(text.length - stripHeader(text).length > 0, true, `${name} has no header`);
		}
	});
}

test('header: first lines, or last lines after the body for shell scripts', () => {
	const r = genOk();
	const header = [
		`${HEADER_PREFIX}generated by small-elasticsearch-lab generator ${GENERATOR_VERSION}; data verified ${data.meta.versions_checked}\n`,
		`${HEADER_PREFIX}tested scenario: scenarios/es-single@${data.meta.companion_tag}\n`,
	].join('');
	for (const [name, text] of Object.entries(r.files)) {
		if (name.endsWith('.sh')) {
			assert.ok(text.startsWith('#!/usr/bin/env bash\n'), name);
			assert.ok(text.endsWith(`\n${header}`), name);
		} else {
			assert.ok(text.startsWith(header), name);
		}
	}
});

