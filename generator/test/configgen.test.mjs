test('CIDR validation', () => {
	const ok = ['127.0.0.1/32', '10.0.0.0/8', '0.0.0.0/0', '192.168.0.0/16', '::1/128', '2001:db8::/32', 'fe80::/10',
		'::/0', '2001:db8:0:0:0:0:0:0/128', '::ffff:192.0.2.0/120', '2001:DB8::/32'];
	for (const c of ok) assert.equal(parseCidr(c).error, undefined, c);
	const bad = {
		'127.0.0.1': /prefix length/,
		'::1': /prefix length/,
		'10.0.0.1/8': /host bits set; the network is 10.0.0.0\/8/,
		'2001:db8::1/32': /host bits set; the network is 2001:db8::\/32/,
		'256.0.0.0/8': /not an IPv4 or IPv6 CIDR/,
		'010.0.0.0/8': /not an IPv4 or IPv6 CIDR/,
		'10.0.0/24': /not an IPv4 or IPv6 CIDR/,
		'10.0.0.0/33': /at most \/32/,
		'::/129': /at most \/128/,
		'10.0.0.0/08': /leading zero/,
		'1::2::3/64': /not an IPv4 or IPv6 CIDR/,
		'1:2:3:4:5:6:7:8:9/128': /not an IPv4 or IPv6 CIDR/,
		'1:2:3:4:5:6:7/128': /not an IPv4 or IPv6 CIDR/,
		'fe80::1%eth0/128': /not an IPv4 or IPv6 CIDR/,
		'1.2.3.4::/64': /not an IPv4 or IPv6 CIDR/,
		'example.com/32': /not an IPv4 or IPv6 CIDR/,
		'10.0.0.0/': /not an IPv4 or IPv6 CIDR/,
	};
	for (const [c, re] of Object.entries(bad)) assert.match(parseCidr(c).error ?? '', re, c);

	assert.ok(validate({ allowedCidrs: [] }).errors.some((e) => e.field === 'allowedCidrs'));
	assert.ok(validate({ allowedCidrs: ['10.0.0.0/8', '10.0.0.0/8'] }).errors.some((e) => /twice/.test(e.message)));
	assert.ok(validate({ allowedCidrs: Array.from({ length: 65 }, (_, i) => `10.0.${i}.0/24`) }).errors.length);
	assert.ok(validate({ allowedCidrs: ['0.0.0.0/0'] }).warnings.some((w) => /every address/.test(w.message)));
	assert.deepEqual(validate({ allowedCidrs: '10.0.0.0/8\n192.168.0.0/16' }).values.allowedCidrs, ['10.0.0.0/8', '192.168.0.0/16']);
});

